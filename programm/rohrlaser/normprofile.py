def _name(reihe, groesse):
    return f"{reihe} {groesse}"


def alle():
    """Alle Normprofile mit Querschnitt: {Name: dict(reihe, form, h, b, tw, tf, r, flaeche mm², geneigt)}."""
    out = {}
    for reihe, form, geneigt, tab in REIHEN:
        for g, (h, b, tw, tf, r, a) in tab.items():
            out[_name(reihe, g)] = dict(reihe=reihe, form=form, h=h, b=b, tw=tw, tf=tf, r=r, flaeche=a * 100,
                                        geneigt=geneigt)
    for a, b, t in WINKEL:
        n = f"L {a:g}x{b:g}x{t:g}"
        out[n] = dict(reihe="L", form="L-Profil", h=a, b=b, tw=t, tf=t, r=None, flaeche=None, geneigt=False)
    return out


NORM = alle()


def daten(name):
    """Normprofil zum Namen (z. B. 'IPE 200', 'HEB 160', 'UPN 100', 'T 50') oder None."""
    return NORM.get(" ".join(str(name or "").split()))


def zuordnen(form, h, b, tw, tf, flaeche=None):
    """Name des passenden Normprofils oder None. Nur bei ausreichend genauer Übereinstimmung aller Maße (und der
    Fläche, wenn die Tabelle eine hat); bei mehreren Treffern der mit der kleinsten Abweichung."""
    best = None
    for name, n in NORM.items():
        if n["form"] != form:
            continue
        if form == "L-Profil":
            ok = abs(max(h, b) - n["h"]) <= TOL_HB and abs(min(h, b) - n["b"]) <= TOL_HB and abs(tw - n["tw"]) <= TOL_T
        else:
            tol_t = TOL_T_GENEIGT if n["geneigt"] else TOL_T
            ok = (abs(h - n["h"]) <= TOL_HB and abs(b - n["b"]) <= TOL_HB and abs(tw - n["tw"]) <= tol_t
                  and abs(tf - n["tf"]) <= tol_t)
            if ok and flaeche and n["flaeche"]:
                ok = abs(flaeche - n["flaeche"]) <= TOL_A * n["flaeche"]
        if ok:
            abw = abs(h - n["h"]) + abs(b - n["b"]) + abs(tw - n["tw"]) + abs(tf - n["tf"])
            if best is None or abw < best[0]:
                best = (abw, name)
    return best[1] if best else None
