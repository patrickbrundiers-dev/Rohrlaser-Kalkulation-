"""Messlauf SQLite gegen PostgreSQL über die Verbindungsschicht (Plan Datenbank-Modernisierung 12.11.2026, Basis für
Phase 8). Nur Entwicklung, nicht im Programm.

Misst mit erzeugten Daten (keine Kundendaten): Anlegen von N Angeboten in einer Transaktion, Angebotsliste, Suche
„enthält“, Einzeländerung (eine Transaktion je Zellenänderung wie im Programm) und gleichzeitiges Speichern aus
1/5/10/25/50 Threads. PostgreSQL läuft als eingebetteter Server (pg_lokal) in einem Testordner.

Aufruf: python werkzeuge/db_vergleich.py [--angebote 10000] [--json DATEI]
"""
import argparse
import json
import random
import statistics
import sys
import tempfile
import threading
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "programm"))
from rohrlaser import db_verbindung as dv  # noqa: E402
from rohrlaser import pg_lokal  # noqa: E402

KUNDEN = ["Müller Stahlbau", "Meier Metall", "Schmidt Anlagen", "Becker Fördertechnik", "Wagner Gestelle"]


def messen(name, fabrik, auto, n):
    w = {}
    v = fabrik()
    v.execute(f"CREATE TABLE angebote (id INTEGER PRIMARY KEY{auto}, nummer TEXT UNIQUE, kunde TEXT, "
              "bemerkung TEXT, betrag REAL, datum TEXT, version INTEGER NOT NULL DEFAULT 1)")
    rnd = random.Random(1)
    zeilen = [(f"2026-{i:05d}", rnd.choice(KUNDEN), f"Rahmen {rnd.randint(1, 999)} verzinkt", rnd.uniform(50, 9000),
               f"2026-{rnd.randint(1, 12):02d}-{rnd.randint(1, 28):02d}") for i in range(n)]
    t = time.perf_counter()
    with v.transaktion():
        v.executemany("INSERT INTO angebote (nummer, kunde, bemerkung, betrag, datum) VALUES (?, ?, ?, ?, ?)", zeilen)
    w["anlegen_s"] = time.perf_counter() - t
    t = time.perf_counter()
    v.execute("SELECT id, nummer, kunde, betrag FROM angebote ORDER BY datum DESC, id DESC").fetchall()
    w["liste_s"] = time.perf_counter() - t
    t = time.perf_counter()
    v.execute("SELECT id FROM angebote WHERE kunde LIKE ? OR bemerkung LIKE ?", ("%etall%", "%477%")).fetchall()
    w["suche_s"] = time.perf_counter() - t
    t = time.perf_counter()
    for i in range(1, 201):
        with v.transaktion():
            v.execute("UPDATE angebote SET betrag=betrag+1 WHERE id=?", (i,))
    w["zelle_aendern_ms"] = (time.perf_counter() - t) / 200 * 1000
    for benutzer in (1, 5, 10, 25, 50):
        zeiten = []
        sperre = threading.Lock()

        def arbeiten(nr):
            c = fabrik()
            eigene = []
            for k in range(20):
                ziel = 1 + (nr * 20 + k) % n
                s = time.perf_counter()
                for _ in range(100):
                    try:
                        with c.transaktion():
                            c.execute("UPDATE angebote SET betrag=betrag+1 WHERE id=?", (ziel,))
                        break
                    except (dv.VerbindungWeg, dv.Konflikt):
                        time.sleep(0.01)
                eigene.append(time.perf_counter() - s)
            c.schliessen()
            with sperre:
                zeiten.extend(eigene)

        threads = [threading.Thread(target=arbeiten, args=(i,)) for i in range(benutzer)]
        t = time.perf_counter()
        for th in threads:
            th.start()
        for th in threads:
            th.join()
        gesamt = time.perf_counter() - t
        zeiten.sort()
        w[f"benutzer_{benutzer}"] = dict(speichern_median_ms=statistics.median(zeiten) * 1000,
                                         speichern_p95_ms=zeiten[int(len(zeiten) * 0.95) - 1] * 1000,
                                         speichern_je_s=len(zeiten) / gesamt)
    v.schliessen()
    print(name, json.dumps(w, indent=1))
    return w


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--angebote", type=int, default=10000)
    ap.add_argument("--json")
    a = ap.parse_args()
    tmp = Path(tempfile.mkdtemp())
    ergebnis = {"angebote": a.angebote}
    ergebnis["sqlite"] = messen("SQLite", lambda: dv.oeffnen({"art": "sqlite", "pfad": tmp / "m.sqlite"}), "", a.angebote)
    server = pg_lokal.LokalerServer(tmp / "Daten")
    server.starten()
    try:
        ergebnis["postgres"] = messen("PostgreSQL", lambda: dv.oeffnen(server.zugang(), passwort=server.passwort),
                                      " GENERATED BY DEFAULT AS IDENTITY", a.angebote)
    finally:
        server.stoppen()
    if a.json:
        Path(a.json).write_text(json.dumps(ergebnis, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
